"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const root=path.resolve(__dirname,"..");
const variants=["classic-spearhead","crystal-tech-shard","elven-feather","hollow-frame","rune-edged","minimal-precision"];
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const page=read("newtab.html"), js=read("newtab.js"), css=read("styles.css");
for(const name of variants){
  const pathName="assets/cursors/"+name+".png";
  const bytes=fs.readFileSync(path.join(root,pathName));
  assert(bytes.length>300,"cursor asset is empty: "+name);
  assert.equal(bytes.subarray(0,8).toString("hex"),"89504e470d0a1a0a",name+" must be PNG");
  assert.equal(bytes.readUInt32BE(16),64,name+" PNG width");
  assert.equal(bytes.readUInt32BE(20),64,name+" PNG height");
  assert(bytes.includes(Buffer.from("tRNS")),name+" needs alpha transparency");
  assert(page.includes('value="'+name+'"'),name+" setting missing");
  assert(page.includes('src="'+pathName+'"'),name+" image preview missing");
}
assert(page.includes('name="cursor-choice" value="system" checked'),"custom cursor must be opt-in");
assert(/const workspaceFields=\[[^\]]*"cursor"[^\]]*"typography"[^\]]*\]/.test(js),"cursor must have a separate persisted workspace field");
assert(js.includes('const cleanCursor=value=>'),"imported cursor values need strict allowlisting");
assert(js.includes('document.body.style.setProperty("--elf-custom-cursor"'),"cursor must be applied only from allowlist");
assert(js.includes('persist(["links","bangs","motion","contrast","cursor","typography"])'),"cursor setting must persist with typography and other settings");
assert(css.includes('body[data-cursor]:not([data-cursor="system"])'),"cursor must remain opt-in");
assert(css.includes("cursor:var(--elf-text-cursor,text)"),"editing text must retain native I-beam fallback");
const pure=js.slice(0,js.indexOf('$("search-form").addEventListener'));
const context={URL,Date,Intl,console,setTimeout,clearTimeout};
vm.createContext(context);
vm.runInContext(pure,context,{timeout:2000});
const run=expr=>vm.runInContext(expr,context,{timeout:1000});
assert.equal(run('cleanCursor("rune-edged")'),"rune-edged");
assert.equal(run('cleanCursor("system")'),"system");
assert.equal(run('cleanCursor("../../data")'),"system");
assert.equal(run('cleanCursor(null)'),"system");
assert.equal(run('cleanWorkspace({links:defaults, note:"", focus:""}).cursor'),"system");
assert.equal(run('cleanWorkspace({links:defaults, cursor:"hollow-frame"}).cursor'),"hollow-frame");
console.log("Ay arime six cursor assets, opt-in selection, safety and persistence checks passed.");
